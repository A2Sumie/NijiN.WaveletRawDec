bool probe_arw6_codestream(
    const uint8_t* data,
    size_t len,
    Arw6Info& info,
    std::string& err) {
    info = Arw6Info();
    if (!data || len < 16) {
        err = "ARW6 codestream truncated before 16-byte header";
        return false;
    }
    if (std::memcmp(data, "A000", 4) != 0) {
        err = "Missing A000 signature in ARW6 codestream";
        return false;
    }
    uint16_t w = rd_be16(data + 8);
    uint16_t half_h = rd_be16(data + 10);
    uint16_t bd_raw = rd_be16(data + 12);
    uint16_t coded_bd = (bd_raw >> 4) & 0x3Fu;
    uint8_t b14 = data[14];
    uint8_t b15 = data[15];

    uint8_t num_comps = b14 >> 5;
    uint8_t decomp_levels = (b14 >> 2) & 3u;
    uint16_t sub_mask = static_cast<uint16_t>((static_cast<uint16_t>(b14 & 3u) << 8) | b15);

    if (num_comps != 3 || decomp_levels != 3 || sub_mask != 0x0200u ||
        coded_bd < 10u || coded_bd > 16u || w < 2u || half_h < 1u || (w & 1u) != 0u) {
        err = "Unsupported ARW6 codestream parameters";
        return false;
    }

    info.width = w;
    info.height = static_cast<uint32_t>(half_h) * 2u;
    info.codestream_size = static_cast<uint32_t>(len);
    info.bit_depth = 14;
    info.internal_depth = 12;
    info.coded_depth = coded_bd;
    info.num_comps = num_comps;
    info.decomp_levels = decomp_levels;
    info.subsampling_mask = sub_mask;
    return true;
}

bool probe_arw6_strip(
    const uint8_t* strip_data,
    size_t strip_len,
    Arw6Info& info,
    std::string& err) {
    info = Arw6Info();
    if (!strip_data || strip_len < 0x68) {
        err = "ARW6 strip smaller than 0x68-byte tile directory";
        return false;
    }
    uint64_t tile_cnt = rd_le64(strip_data);
    if (tile_cnt != 1 && tile_cnt != 4) {
        err = "Unsupported ARW6 tile count: " + std::to_string(tile_cnt);
        return false;
    }
    uint64_t min_rel = 8ULL + tile_cnt * 24ULL;
    std::vector<Arw6TileInfo> tiles(static_cast<size_t>(tile_cnt));
    std::vector<uint64_t> sorted_offs;
    sorted_offs.reserve(static_cast<size_t>(tile_cnt));

    uint32_t full_w = 0;
    uint32_t full_h = 0;
    for (uint64_t i = 0; i < tile_cnt; ++i) {
        const uint8_t* td = strip_data + 8 + i * 24;
        Arw6TileInfo& ti = tiles[i];
        ti.rel_offset = rd_le64(td);
        ti.x = rd_le32(td + 8);
        ti.y = rd_le32(td + 12);
        ti.width = rd_le32(td + 16);
        ti.height = rd_le32(td + 20);
        if (ti.rel_offset < min_rel || ti.rel_offset + 16 > strip_len ||
            ti.width < 2 || ti.height < 2 || (ti.width & 1u) != 0 || (ti.height & 1u) != 0) {
            err = "Invalid ARW6 tile descriptor at index " + std::to_string(i);
            return false;
        }
        if ((ti.x & 1u) != 0 || (ti.y & 1u) != 0) {
            err = "ARW6 tile origin must align to 2x2 CFA grid";
            return false;
        }
        sorted_offs.push_back(ti.rel_offset);
        full_w = std::max(full_w, ti.x + ti.width);
        full_h = std::max(full_h, ti.y + ti.height);
    }

    std::sort(sorted_offs.begin(), sorted_offs.end());
    for (size_t i = 1; i < sorted_offs.size(); ++i) {
        if (sorted_offs[i] <= sorted_offs[i - 1]) {
            err = "Duplicate ARW6 tile offsets";
            return false;
        }
    }

    for (size_t i = 0; i < tiles.size(); ++i) {
        uint64_t end_off = strip_len;
        auto it = std::upper_bound(sorted_offs.begin(), sorted_offs.end(), tiles[i].rel_offset);
        if (it != sorted_offs.end()) {
            end_off = *it;
        }
        tiles[i].data_size = static_cast<uint32_t>(end_off - tiles[i].rel_offset);
        Arw6Info tinfo;
        if (!probe_arw6_codestream(strip_data + tiles[i].rel_offset, tiles[i].data_size, tinfo, err)) {
            return false;
        }
        if (tinfo.width != tiles[i].width || tinfo.height != tiles[i].height) {
            err = "ARW6 tile header dimensions disagree with codestream header";
            return false;
        }
        if (i == 0) {
            info = tinfo;
        }
    }

    info.width = full_w;
    info.height = full_h;
    info.codestream_size = static_cast<uint32_t>(strip_len);
    info.tiles = std::move(tiles);
    return true;
}

bool decode_arw6_tile(
    const uint8_t* cs_data,
    size_t cs_len,
    int num_threads,
    uint32_t tile_x,
    uint32_t tile_y,
    uint32_t full_w,
    uint32_t full_h,
    std::vector<uint16_t>& bayer_out,
    Arw6Info& tile_info_out,
    std::string& err) {
    if (!cs_data || cs_len < 16) {
        err = "Empty ARW6 tile codestream";
        return false;
    }
    Arw6Info probed;
    if (!probe_arw6_codestream(cs_data, cs_len, probed, err)) {
        return false;
    }
    uint32_t tw = (full_w == 0) ? probed.width : full_w;
    uint32_t th = (full_h == 0) ? probed.height : full_h;
    if (bayer_out.size() != static_cast<size_t>(tw) * th) {
        bayer_out.assign(static_cast<size_t>(tw) * th, 0);
    }
    return decode_arw6_codestream_internal(
        cs_data, cs_len, num_threads, tile_x, tile_y, tw, th, bayer_out, tile_info_out, err);
}

bool decode_arw6_bayer(
    const uint8_t* strip_data,
    size_t strip_len,
    int num_threads,
    std::vector<uint16_t>& bayer_out,
    Arw6Info& info_out,
    std::string& err) {
    if (!probe_arw6_strip(strip_data, strip_len, info_out, err)) {
        return false;
    }
    bayer_out.assign(static_cast<size_t>(info_out.width) * static_cast<size_t>(info_out.height), 0);
    for (size_t i = 0; i < info_out.tiles.size(); ++i) {
        const Arw6TileInfo& ti = info_out.tiles[i];
        Arw6Info tinfo;
        if (!decode_arw6_codestream_internal(
                strip_data + ti.rel_offset, ti.data_size, num_threads,
                ti.x, ti.y, info_out.width, info_out.height, bayer_out, tinfo, err)) {
            return false;
        }
    }
    return true;
}

